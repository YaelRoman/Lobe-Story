const TILTS: [string, TiltSettings][] = [
  ['e3', { electricalDeg: 3, mechanicalDeg: 0 }],
  ['m6', { electricalDeg: 0, mechanicalDeg: 6 }],
  ['e-2m4', { electricalDeg: -2, mechanicalDeg: 4 }],
];

const tagged: TaggedPattern[] = [0, 7, 13, 22].map((i) => {
  const f = exampleFiles()[i];
  const r = parsePlanet(f.text, f.name);
  if (!r.ok) throw new Error(r.error);
  return { pattern: r.pattern, tags: {} };
});

const values = (m: Map<string, PatternMetrics>): number[] =>
  tagged.flatMap((t) => {
    const a = m.get(t.pattern.id)!.are;
    return [a.sector.value!, a.spatial.value!, a.lower.value!];
  });

const same = (now: number[], earlier: number[]) => {
  expect(now).toHaveLength(earlier.length);
  now.forEach((x, i) => expect(Object.is(x, earlier[i])).toBe(true));
};

describe('with the back of the vertical cut off, the angular-region estimate is the earlier one', () => {
  for (const method of ['summation', 'weighted'] as const) {
    it(`${method}, untilted`, () => {
      same(values(analyzeAll(tagged, DEFAULT_SETTINGS, { areMethod: method })), EARLIER[`${method}|untilted`]);
      same(values(analyzeAll(tagged, DEFAULT_SETTINGS, { areMethod: method, areBackHalf: false })), EARLIER[`${method}|untilted`]);
    });

    it(`${method}, under each kind of tilt and either horizontal cut`, () => {
      for (const [name, t] of TILTS)
        for (const hCut of ['beam', 'horizon'] as const) {
          const key = `${method}|${name}|${hCut}`;
          same(values(analyzeTilted(tiltEach(tagged, () => t, method, hCut), DEFAULT_SETTINGS, () => t, method)), EARLIER[key]);
          same(values(analyzeTilted(tiltEach(tagged, () => t, method, hCut, false), DEFAULT_SETTINGS, () => t, method, false)), EARLIER[key]);
        }
    }, 30_000);
  }
});
